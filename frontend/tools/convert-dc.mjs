// 프로토타입 dc.html(x-dc 템플릿 + DCLogic 스크립트)을 Preact(HTM) 소스로 변환한다.
// 프로토타입이 갱신되면 다시 실행해 src/view.js·src/app.js를 재생성한다.
//
// 사용: node tools/convert-dc.mjs "<dc.html 경로>"
// 산출: src/view.js   — 템플릿 → view(v) 렌더 함수 (htm 템플릿 리터럴)
//       src/app.js    — DCLogic 클래스 → preact/compat Component (본문 무수정 이식)
//       src/styles/hover.css — style-hover 속성 → :hover 클래스
//
// 변환 규칙:
//   {{ expr }}                → ${expr}   (루트 식별자는 view(v)에서 구조분해)
//   attr="{{ expr }}"         → attr=${expr}   (비문자열 값 전달 위해 따옴표 제거)
//   <sc-if value="{{c}}">X    → ${(c) ? html`X` : null}
//   <sc-for list="{{l}}" as=x → ${(l || []).map((x) => html`X`)}
//   style-hover="css"         → class="vhovN" + hover.css 규칙
//   hint-placeholder-*        → 제거 (dc 프리뷰 힌트)
//   <input|img|br|hr ...>     → 자기닫힘 (htm 요구)

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
// 인자 생략 시 작업 레포(neo-pkg-replication)의 프로토타입 위치를 기본값으로 사용
const DEFAULT_DC = path.join(__dirname, '..', '..', '진동 데이터 분석 패키지', '진동 분석 패키지.dc.html');
const srcPath = process.argv[2] || (fs.existsSync(DEFAULT_DC) ? DEFAULT_DC : null);
if (!srcPath) { console.error('usage: node tools/convert-dc.mjs <dc.html>'); process.exit(1); }
const raw = fs.readFileSync(srcPath, 'utf8');

// ---------- 추출 ----------
const helmetEnd = raw.indexOf('</helmet>');
const xdcEnd = raw.lastIndexOf('</x-dc>');
if (helmetEnd < 0 || xdcEnd < 0) { console.error('x-dc template not found'); process.exit(1); }
let tpl = raw.slice(helmetEnd + '</helmet>'.length, xdcEnd);

const smStart = raw.indexOf('data-dc-script');
const scriptOpenEnd = raw.indexOf('>', smStart);
const scriptClose = raw.indexOf('</script>', scriptOpenEnd);
let logic = raw.slice(scriptOpenEnd + 1, scriptClose).trim();

// ---------- 안전성 검사 ----------
if (tpl.includes('`')) { console.error('template contains backtick — escape needed'); process.exit(1); }
const badEntity = tpl.match(/&(?!amp;|lt;|gt;|quot;|#)[a-z]+;/);
if (badEntity) console.warn('WARN: HTML entity in template (htm은 디코딩 안함):', badEntity[0]);

// ---------- 루트 식별자 수집 (구조분해용) ----------
const ids = new Set();
for (const m of tpl.matchAll(/\{\{\s*!?\s*([A-Za-z_$][\w$]*)/g)) ids.add(m[1]);
const loopVars = new Set();
for (const m of tpl.matchAll(/<sc-for\b[^>]*\bas="([^"]+)"/g)) loopVars.add(m[1]);
for (const lv of loopVars) ids.delete(lv);
ids.delete('true'); ids.delete('false');

// ---------- 템플릿 변환 ----------
tpl = tpl.replace(/\s+hint-placeholder-(count|val)="[^"]*"/g, '');

const hoverMap = new Map();
tpl = tpl.replace(/\s+style-hover="([^"]*)"/g, (m, css) => {
  if (!hoverMap.has(css)) hoverMap.set(css, 'vhov' + (hoverMap.size + 1));
  return ' class="' + hoverMap.get(css) + '"';
});

tpl = tpl.replace(/<(input|img|br|hr)((?:[^>"]|"[^"]*")*?)\s*\/?>/g, '<$1$2 />');

function transform(s) {
  let out = '';
  let i = 0;
  const re = /<sc-(if|for)\b[^>]*>/g;
  for (;;) {
    re.lastIndex = i;
    const m = re.exec(s);
    if (!m) { out += s.slice(i); break; }
    out += s.slice(i, m.index);
    const kind = m[1];
    const openTag = '<sc-' + kind;
    const closeTag = '</sc-' + kind + '>';
    let depth = 1, j = m.index + m[0].length;
    while (depth > 0) {
      const nextOpen = s.indexOf(openTag, j);
      const nextClose = s.indexOf(closeTag, j);
      if (nextClose === -1) throw new Error('unbalanced sc-' + kind);
      if (nextOpen !== -1 && nextOpen < nextClose) { depth++; j = nextOpen + openTag.length; }
      else { depth--; j = depth === 0 ? nextClose : nextClose + closeTag.length; }
    }
    const inner = transform(s.slice(m.index + m[0].length, j));
    if (kind === 'if') {
      const vm = /value="\{\{(.*?)\}\}"/.exec(m[0]);
      if (!vm) throw new Error('sc-if without value: ' + m[0]);
      out += '${(' + vm[1].trim() + ') ? html`' + inner + '` : null}';
    } else {
      const lm = /list="\{\{(.*?)\}\}"/.exec(m[0]);
      const am = /as="([^"]+)"/.exec(m[0]);
      if (!lm || !am) throw new Error('sc-for missing list/as: ' + m[0]);
      out += '${(' + lm[1].trim() + ' || []).map((' + am[1] + ') => html`' + inner + '`)}';
    }
    i = j + closeTag.length;
  }
  return out;
}
tpl = transform(tpl);

// 속성 전체가 단일 바인딩이면 따옴표 제거(함수/불리언 전달), 나머지는 문자열 보간
tpl = tpl.replace(/([a-zA-Z][\w-]*)="\{\{\s*(.*?)\s*\}\}"/g, (m, attr, expr) => attr + '=${' + expr + '}');
tpl = tpl.replace(/\{\{\s*(.*?)\s*\}\}/g, (m, e) => '${' + e + '}');

const idList = [...ids].sort();
const viewOut = `// GENERATED by tools/convert-dc.mjs — 직접 수정 금지, 프로토타입 dc.html에서 재생성.
import { html } from './html.js';

export function view(v) {
  const {
    ${idList.join(', ')}
  } = v;
  return html\`${tpl}\`;
}
`;

// ---------- 로직 클래스 변환 ----------
if (!logic.includes('class Component extends DCLogic {')) {
  console.error('DCLogic class header not found'); process.exit(1);
}
logic = logic.replace('class Component extends DCLogic {', 'export class App extends Component {');
logic = logic.replace(/\}\s*$/, '\n  render() { return view(this.renderVals()); }\n}\n');
const appOut = `// GENERATED by tools/convert-dc.mjs — 본문은 프로토타입 DCLogic 클래스 그대로.
// LLM 소견(window.claude.complete)은 미탑재 시 폴백 경로로 동작한다(P4에서 opinion CGI로 대체).
import { Component } from 'preact/compat';
import { view } from './view.js';

${logic}`;

// ---------- 산출 ----------
// app.js는 P2(실데이터 연동)부터 수동 유지 — --with-app 플래그를 줄 때만 재생성(수동 수정 클로버 방지)
const srcDir = path.join(__dirname, '..', 'src');
fs.writeFileSync(path.join(srcDir, 'view.js'), viewOut);
if (process.argv.includes('--with-app')) {
  fs.writeFileSync(path.join(srcDir, 'app.js'), appOut);
  console.log('app.js REGENERATED (--with-app) — 수동 수정이 있었다면 유실됨 주의');
}
const hoverCss = [...hoverMap.entries()].map(([css, cls]) => '.' + cls + ':hover { ' + css + ' }').join('\n') + '\n';
fs.writeFileSync(path.join(srcDir, 'styles', 'hover.css'), hoverCss);

console.log('view.js ids:', idList.length, '| loop vars:', [...loopVars].join(','), '| hover classes:', hoverMap.size);
