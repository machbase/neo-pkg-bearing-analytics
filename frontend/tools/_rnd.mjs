// 결정론 난수 — 회귀 판정에 Math.random을 쓸 수 없어 자체 생성기를 쓴다.
//
// ⚠ 예전에 쓰던 `seed = (seed * 1103515245 + 12345) & 0x7fffffff`는 **쓰면 안 된다**.
// seed가 2^31에 가까워지면 곱이 2.4e18로 Number.MAX_SAFE_INTEGER(9.0e15)를 넘어
// 저비트가 반올림으로 소실되고, 상태 주기가 1만 남짓으로 붕괴한다.
// 그러면 "백색잡음"이 분석창 안에서 여러 번 반복되는 **주기 신호**가 되어,
// 조밀한 하모닉 숲이 생기고 어떤 주파수 판별자든 오발한다.
// (실제로 이 버그 때문에 측대역 판독이 "잡음에서도 걸린다"는 잘못된 결론으로 폐기됐었다.
//  Welch 평탄도로는 안 드러난다 — 포락선 스펙트럼의 고분해능에서만 보인다.)
//
// mulberry32는 Math.imul로 32비트 안에서만 곱해 이 문제가 없다.
export function mulberry32(seed) {
  let a = seed >>> 0;
  return function () {
    a = (a + 0x6D2B79F5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return (((t ^ (t >>> 14)) >>> 0) / 4294967296) * 2 - 1;   // [-1, 1)
  };
}
